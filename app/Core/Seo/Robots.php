<?php

namespace App\Core\Seo;

use App\Core\Storefronts\LocaleResolver;

/**
 * The shop's robots.txt, composed rather than kept as a file.
 *
 * It used to be `public/robots.txt`, two lines that said "everything is
 * allowed" and could say nothing else: what a shop wants to tell a crawler
 * depends on which modules it has (a cart is not worth indexing, a sitemap has
 * to be announced) and on a decision only the owner can take — whether AI
 * agents are welcome, and which ones. A static file cannot hold either, and a
 * file WRITTEN by the engine would be a second copy of a setting that drifts
 * the moment somebody edits it by hand.
 *
 * In core, not in a module: a shop has a robots.txt whether or not it has a
 * catalogue, and the answer must not disappear with an uninstall. What core
 * does NOT know is which paths are worth hiding — `/cart` belongs to checkout —
 * so modules add their own through `core.robots.disallow`, and the sitemap
 * announces itself through `core.robots.sitemaps`.
 *
 * Two audiences, because they are two different bargains. An ASSISTANT fetches
 * one page because a person asked a question about it, and sends that person
 * back as a visitor; a TRAINING crawler takes the catalogue and gives nothing
 * back, and nothing can be untrained afterwards. So the engine's defaults are
 * "assistants yes, training no", both reversible in one click, and WHICH agents
 * are in which list is a setting rather than a constant: the list changes
 * monthly and a shop owner must not have to wait for a release to add a name.
 */
class Robots
{
    public static function render(): string
    {
        $rules = self::rules();
        $out = [];

        $out[] = '# Generated by the shop — edit it in Settings → Core → AI agents and crawlers.';
        $out[] = '';
        $out[] = 'User-agent: *';
        $out = [...$out, ...$rules, ''];

        // A named group REPLACES the `*` group for the agent it names — a
        // crawler that finds itself listed never reads the star rules at all.
        // So an allowed assistant is handed the same disallows again; without
        // them, inviting one agent would open the admin path to it alone.
        foreach (self::groups() as $group) {
            if ($group['agents'] === []) {
                continue;
            }

            $out[] = '# '.$group['comment'].'.';

            foreach ($group['agents'] as $agent) {
                $out[] = 'User-agent: '.$agent;
            }

            $out = [...$out, ...($group['allowed'] ? [...$rules, 'Allow: /'] : ['Disallow: /']), ''];
        }

        foreach (self::sitemaps() as $sitemap) {
            $out[] = 'Sitemap: '.$sitemap;
        }

        if ($extra = trim((string) setting('core', 'robots_extra', ''))) {
            $out[] = '';
            $out[] = $extra;
        }

        return implode("\n", $out)."\n";
    }

    /**
     * The `Disallow:` lines every group gets — what has no business in any
     * index at all.
     *
     * Most of it is not written here at all: {@see PrivateRoutes} holds the
     * route names nobody should index — core's account pages, a module's cart
     * and checkout — and turns them into paths off the route table, in every
     * locale shape it has, because `/ru/cart` is a different path to a crawler
     * and the wildcard form that would cover both at once is an extension only
     * some of them understand. The same registry puts `<meta name="robots">` on
     * those pages: one list, two readers.
     *
     * `/admin` stays written down because no route expresses it — it is a
     * prefix, not a page — and `core.robots.disallow` stays for the same kind
     * of thing.
     *
     * @return list<string>
     */
    public static function rules(): array
    {
        $paths = ['/admin', ...app(PrivateRoutes::class)->paths()];

        $paths = array_merge($paths, hook_filter('core.robots.disallow', [], []));

        $lines = [];

        foreach (array_unique($paths) as $path) {
            $lines[] = 'Disallow: '.$path;
        }

        return $lines;
    }

    /**
     * A storefront path in every language shape the route table has — what a
     * module hands back from `core.robots.disallow`, so that hiding `/cart`
     * does not leave `/ru/cart` indexed.
     *
     * @return list<string>
     */
    public static function localised(string $path): array
    {
        $paths = [$path];

        foreach (LocaleResolver::routePrefixes() as $locale) {
            $paths[] = '/'.$locale.$path;
        }

        return $paths;
    }

    /** @return list<array{comment: string, agents: list<string>, allowed: bool}> */
    public static function groups(): array
    {
        return [
            [
                'comment' => 'AI assistants that fetch a page because somebody asked about it',
                'agents' => self::agents('ai_assistant_agents'),
                'allowed' => setting('core', 'ai_assistants', 'allow') === 'allow',
            ],
            [
                'comment' => 'AI crawlers that collect pages to train on',
                'agents' => self::agents('ai_training_agents'),
                'allowed' => setting('core', 'ai_training', 'deny') === 'allow',
            ],
        ];
    }

    /** Does the shop invite machine readers at all — the question llms.txt exists to answer. */
    public static function invitesAgents(): bool
    {
        foreach (self::groups() as $group) {
            if ($group['allowed'] && $group['agents'] !== []) {
                return true;
            }
        }

        return false;
    }

    /**
     * One agent per line, blank lines and `#` comments ignored — the shape a
     * person edits a list in, not a comma-separated field they have to count
     * commas in.
     *
     * @return list<string>
     */
    protected static function agents(string $key): array
    {
        $agents = [];

        foreach (preg_split('/[\r\n,]+/', (string) setting('core', $key, '')) ?: [] as $line) {
            $line = trim($line);

            if ($line !== '' && ! str_starts_with($line, '#')) {
                $agents[] = $line;
            }
        }

        return array_values(array_unique($agents));
    }

    /** @return list<string> */
    protected static function sitemaps(): array
    {
        $sitemaps = hook_filter('core.robots.sitemaps', [], []);

        return array_values(array_unique(array_filter(array_map('trim', $sitemaps))));
    }
}
